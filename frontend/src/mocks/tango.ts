function seenAt(placeId: string, iso: string): Sighting {
  const place = PLACES[placeId];
  return {
    placeId,
    placeName: place.name.meaning ?? place.name.text,
    lat: place.lat,
    lng: place.lng,
    seenAt: iso,
  };
}

