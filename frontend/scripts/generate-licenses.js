#!/usr/bin/env node
/**
 * Writes src/legal/licenses.generated.ts: the license of every package the
 * app ships (production dependencies) plus bundled assets (font, artwork).
 * Run `npm run licenses` after adding or updating dependencies.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'legal', 'licenses.generated.ts');

/** Assets bundled with the app that aren't npm packages. */
const ASSETS = [
  {
    name: 'Murecho (font)',
    version: '',
    license: 'OFL-1.1',
    file: 'assets/fonts/OFL-Murecho.txt',
  },
  {
    name: 'Noto Emoji (hanamaru artwork)',
    version: '',
    license: 'Apache-2.0',
    file: 'assets/licenses/NotoEmoji-Apache-2.0.txt',
  },
];

const LICENSE_FILE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i;

function licenseText(dir) {
  let names;
  try {
    names = fs.readdirSync(dir);
  } catch {
    return '';
  }
  const file = names.find(n => LICENSE_FILE.test(n));
  return file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : '';
}

function authorName(pkg) {
  const a = pkg.author;
  if (typeof a === 'string') {
    return a.replace(/\s*[<(].*$/, '').trim();
  }
  return (a && a.name) || pkg.name;
}

const MIT_TEXT = holder => `MIT License

Copyright (c) ${holder}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.`;

function licenseName(pkg) {
  if (typeof pkg.license === 'string') {
    return pkg.license;
  }
  if (pkg.license && pkg.license.type) {
    return pkg.license.type;
  }
  if (Array.isArray(pkg.licenses)) {
    return pkg.licenses.map(l => l.type || l).join(' OR ');
  }
  return 'Unknown';
}

const tree = JSON.parse(
  execSync('npm ls --omit=dev --all --json --long', {
    cwd: ROOT,
    maxBuffer: 64 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'ignore'],
  }).toString(),
);

const packages = new Map();
(function walk(node) {
  for (const dep of Object.values(node.dependencies || {})) {
    if (!dep.name || !dep.version || !dep.path) {
      continue;
    }
    const key = `${dep.name}@${dep.version}`;
    if (packages.has(key)) {
      continue;
    }
    let pkg = {};
    try {
      pkg = JSON.parse(
        fs.readFileSync(path.join(dep.path, 'package.json'), 'utf8'),
      );
    } catch {
      // Keep going: the entry still lists the name and version.
    }
    packages.set(key, {
      name: dep.name,
      version: dep.version,
      license: licenseName(pkg),
      text: licenseText(dep.path),
      author: authorName(pkg),
    });
    walk(dep);
  }
})(tree);

// Packages without a license file get the standard text of their license.
const apacheText = [...packages.values()].find(
  p => p.license === 'Apache-2.0' && /^\s*Apache License/.test(p.text),
)?.text;
for (const p of packages.values()) {
  if (p.text) {
    continue;
  }
  if (p.license === 'MIT') {
    p.text = MIT_TEXT(p.author);
  } else if (p.license === 'Apache-2.0' && apacheText) {
    p.text = apacheText;
  }
}

const entries = [
  ...ASSETS.map(a => ({
    name: a.name,
    version: a.version,
    license: a.license,
    text: fs.readFileSync(path.join(ROOT, a.file), 'utf8').trim(),
  })),
  ...[...packages.values()]
    .map(({ author, ...p }) => p)
    .sort((a, b) => a.name.localeCompare(b.name)),
];

// Many packages share the same text (e.g. MIT): store each text once.
const texts = [];
const indexOf = new Map();
const rows = entries.map(e => {
  const text = e.text || `${e.license} license. No license file was included.`;
  if (!indexOf.has(text)) {
    indexOf.set(text, texts.length);
    texts.push(text);
  }
  return {
    name: e.name,
    version: e.version,
    license: e.license,
    text: indexOf.get(text),
  };
});

const out = `// Generated by scripts/generate-licenses.js. Do not edit; run \`npm run licenses\`.

export interface LicenseEntry {
  name: string;
  version: string;
  /** SPDX id, e.g. "MIT". */
  license: string;
  /** Index into LICENSE_TEXTS. */
  text: number;
}

export const LICENSE_TEXTS: string[] = ${JSON.stringify(texts, null, 2)};

/** Bundled assets first, then packages A to Z. */
export const LICENSES: LicenseEntry[] = ${JSON.stringify(rows, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(
  `Wrote ${rows.length} entries (${
    texts.length
  } distinct texts) to ${path.relative(ROOT, OUT)}`,
);
